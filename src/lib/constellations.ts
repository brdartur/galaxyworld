/** Расстановка экземпляров созвездий; biasRight — доля, смещённая в правую (свободную) зону */
export function makeConstellationInstances(
  rnd: () => number,
  biasRight = 0.55
): CInst[] {
  const insts: CInst[] = [];
  for (let ci = 0; ci < CONSTELLATIONS.length; ci++) {
    const per = 2 + Math.floor(rnd() * 2);
    for (let k = 0; k < per; k++) {
      insts.push({
        c: ci,
        x: rnd() < biasRight ? 0.55 + rnd() * 0.44 : rnd(),
        y: rnd(),
        s: 0.07 + rnd() * 0.09,
        rot: rnd() * Math.PI * 2,
        vx: (rnd() - 0.5) * 0.0045,
        vy: (rnd() - 0.5) * 0.0028,
        ph: rnd() * 6.28,
      });
    }
  }
  return insts;
}
